"""Write host-ops-test/src/game_text.c: the game's own names (build 25480438) in Traditional Chinese, English and
Simplified Chinese for the menu's templates, factions, missions, planets and planet effects.

python -I -X utf8 gen_game_text.py <strings dir from dump_strings.py> <game image> <catalog_data.c> <game_text.c>

Sources: template rows (game.dll+0x32FEF10, name string at +0x24), mission rows (+0x3773420, name at +0x340), and
exact matches of the catalogue's English names (planets; effects whose matched name belongs to that effect alone).
"""
import collections, json, re, struct, sys

strings_dir, image, catalog_path, out_path = sys.argv[1:5]
S = {c: {int(k): v for k, v in json.load(open(f"{strings_dir}/strings-{c}.json", encoding="utf-8")).items()}
     for c in ("tc", "us", "cn")}
img = open(image, "rb").read()
src = open(catalog_path, encoding="utf-8").read()
STR = re.compile(r'"((?:[^"\\]|\\.)*)"')
by_us = collections.defaultdict(list)
for k, v in S["us"].items():
    by_us[v.strip().upper()].append(k)


def full(i):
    return i is not None and all(S[c].get(i, "").strip() for c in S)


def find(english):
    for k in by_us.get(english.strip().upper(), []):
        if full(k): return k
    return None


def c_str(s):
    s = s.strip().replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")
    return '"' + s + '"'


def text(i):
    if not full(i): return '{ { "", "", "" } }'
    return "{ { " + ", ".join(c_str(S[c][i]) for c in ("tc", "us", "cn")) + " } }"


def entries(start):
    a = src.index(start)
    return [l.strip() for l in src[a:src.index("};", a)].splitlines() if l.strip().startswith("{")]


out = ['#include "game_text.h"', "",
       "/* Generated by analysis/gen_game_text.py from game build 25480438's own text (us, tc, cn). */", ""]

out.append("const GameText template_text[25] = {")
for o in range(25):
    out.append("    " + text(struct.unpack_from("<I", img, 0x32FEF10 + o * 0x490 + 0x24)[0]) + ",")
out.append("};\n")

factions = {2: find("Terminids"), 3: find("Automatons"), 4: find("Illuminate")}
out.append("const GameText faction_text[5] = {")
for f in range(5):
    out.append("    " + text(factions.get(f)) + ",")
out.append("};\n")

out.append("const GameText mission_text[162] = {")
for r in range(162):
    out.append("    " + text(struct.unpack_from("<I", img, 0x3773420 + r * 0x380 + 0x340)[0]) + ",")
out.append("};\n")

planet_names = sorted({STR.findall(l)[0] for l in entries("const PlanetEntry planets[]")} |
                      {STR.findall(l)[0] for l in entries("const BiomeEntry biomes[]")})
rows = [(n, find(n)) for n in planet_names]
rows = [(n, i) for n, i in rows if i is not None]
out.append("const NamedText planet_text[] = {")
out += [f"    {{ {c_str(n)}, {text(i)} }}," for n, i in rows]
out.append("};")
out.append("const size_t planet_text_count = sizeof(planet_text) / sizeof(planet_text[0]);\n")


def effect_match(aliases):
    for a in aliases.split(" | "):
        a = re.sub(r"\s*\((?:Enemies|ENEMIES|experimental)\)\s*$", "", a).strip()
        if len(a) >= 3 and re.search("[A-Za-z]", a):
            i = find(a)
            if i is not None: return i
    return None


effects = []
for l in entries("const VariantEntry variants[]"):
    ids = [int(x) for x in re.findall(r"(\d+)u", l)[:1]]
    effects.append((ids[0], effect_match(STR.findall(l)[-1])))
for l in entries("const PlanetEffectEntry planet_effects[]"):
    effects.append((int(re.findall(r"(\d+)u", l)[0]), effect_match(STR.findall(l)[-1])))
uses = collections.Counter(i for _, i in effects if i is not None)
unique = [(e, i) for e, i in effects if i is not None and uses[i] == 1]
out.append("const IdText effect_text[] = {")
out += [f"    {{ {e}u, {text(i)} }}," for e, i in sorted(set(unique))]
out.append("};")
out.append("const size_t effect_text_count = sizeof(effect_text) / sizeof(effect_text[0]);\n")
open(out_path, "w", encoding="utf-8", newline="\n").write("\n".join(out))
print("templates", sum(1 for o in range(25) if full(struct.unpack_from("<I", img, 0x32FEF10 + o * 0x490 + 0x24)[0])),
      "missions", sum(1 for r in range(162) if full(struct.unpack_from("<I", img, 0x3773420 + r * 0x380 + 0x340)[0])),
      "planets", len(rows), "of", len(planet_names), "effects", len(unique), "of", len(effects))
