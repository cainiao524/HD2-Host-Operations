"""Write host-ops-test/src/mission_catalog.c from a tables.json made by dump_operation_tables.py (game build 25480438).

python -I gen_mission_catalog.py <tables.json> <mission_catalog.c>
Names: Havoc's mission_name_hash.txt by mission ID, else English.json, else the empty string.
"""
import json, sys

D = "F:/Game/A/HD2/HellForge/Havoc/files/dropdowns/"
t = json.load(open(sys.argv[1], encoding="utf-8"))


def hashmap(name):
    out = {}
    for line in open(D + name, encoding="utf-8", errors="replace"):
        line = line.strip()
        if not line or line.startswith("//") or ":" not in line: continue
        k, v = line.split(":", 1)
        if k.strip().isdigit(): out[int(k)] = v.strip()
    return out


names = hashmap("mission_name_hash.txt")
used = {}
for o in t["operations"]:
    for row, w in o["missions"]:
        used.setdefault(row, []).append(o["row"])


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


lines = ['#include "catalog.h"', "",
         "/* Generated by analysis/gen_mission_catalog.py from game build 25480438's mission table (game.dll+0x3773420). */",
         "/* used_by: bit n = operation template n lists this mission. */", "",
         "const MissionEntry mission_catalog[] = {"]
for m in t["missions"]:
    n = names.get(m["id"])
    if not n or n == "None": n = m["name"] if m["name"] != "?" else ""
    mask = 0
    for o in used.get(m["row"], []): mask |= 1 << o
    lines.append(f"    {{ {m['id']}u, {m['row']}u, {m['faction']}u, {m['kind']}u, {m['enabled']}u, "
                 f"{m['range'][0]}u, {m['range'][1]}u, 0x{mask:07x}u, {c_string(n)} }},")
lines += ["};", "", "const size_t mission_catalog_count = sizeof(mission_catalog) / sizeof(mission_catalog[0]);", ""]
open(sys.argv[2], "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print("missions", len(t["missions"]))
